#include<stdio.h>

int main()
{
    char cValue = 'S';          // character variable
    int iValue = 11;            // integer variable
    float fValue = 90.78f;      // float variable
    double dValue = 98.564323;  // double variable

    printf("%c\n",cValue);      // print char
    printf("%d\n",iValue);      // print int
    printf("%f\n",fValue);      // print float
    printf("%lf\n",dValue);     // print double
    
    return 0;                   // return from main
}
